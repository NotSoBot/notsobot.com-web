// a server's settings routes, the same under `/users/@me/guilds` (servers you're in, checked against your Discord
// permissions) and `/admin/guilds` (staff, any server)
export type GuildScope = 'me' | 'admin';

export function guildEndpoints(scope: GuildScope, guildId: string) {
  const base = (scope === 'admin') ? ApiEndpoints.ADMIN_GUILD(guildId) : ApiEndpoints.USER_ME_GUILD(guildId);
  return {
    GUILD: base,
    PREFIXES: `${base}/prefixes`,
    PREFIXES_DELETE: `${base}/prefixes/delete`,
    RULES: `${base}/rules`,
    RULES_DELETE: `${base}/rules/delete`,
    RULE: (ruleId: string) => `${base}/rules/${ruleId}`,
    LOGGERS_DELETE: `${base}/loggers/delete`,
    LLM_KNOWLEDGE: `${base}/llm/knowledge`,
    LLM_KNOWLEDGE_ITEM: (knowledgeId: string) => `${base}/llm/knowledge/${knowledgeId}`,
    MUSIC: `${base}/music`,
    MUSIC_CONTROL: `${base}/music/control`,
    MUSIC_QUEUE_DELETE: `${base}/music/queue/delete`,
    MUSIC_QUEUE_ITEM: (itemId: string) => `${base}/music/queue/${itemId}`,
    WARNINGS: `${base}/warnings`,
    WARNINGS_DELETE: `${base}/warnings/delete`,
    WARNING: (warningId: string) => `${base}/warnings/${warningId}`,
    REPORTS: `${base}/reports`,
    REPORT: (reportId: string) => `${base}/reports/${reportId}`,
    REPORT_MESSAGES: (reportId: string) => `${base}/reports/${reportId}/messages`,
    REPORT_QUOTE: (reportId: string) => `${base}/reports/${reportId}/quote`,
    REPORT_MEMBER: (reportId: string) => `${base}/reports/${reportId}/member`,
    DATA_EXPORT: `${base}/data/export`,
    DATA_DELETE: `${base}/data/delete`,
  };
}


